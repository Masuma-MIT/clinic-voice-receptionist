CREATE VIEW public."appointment_overview" WITH (security_invoker=true) AS
 SELECT a.appointment_id,
    a.patient_name,
    a.status,
    a.last_action,
        CASE
            WHEN a.status = 'booked'::text AND a.reschedule_count > 0 THEN 'rescheduled'::text
            ELSE a.status
        END AS display_status,
    sv.service_name,
    sv.department,
    d.doctor_name,
    s.appointment_date,
    s.appointment_time,
    s.consultation_mode,
    a.reason_for_visit,
    a.created_at,
    a.updated_at,
    a.last_rescheduled_at,
    a.reschedule_count,
    a.slot_id,
    a.doctor_id,
    s.service_id,
    ( SELECT manifest.captured_at
           FROM clinic_backup_details_v1.manifest) AS history_tracking_started_at
   FROM appointments a
     LEFT JOIN slots s ON s.slot_id = a.slot_id
     LEFT JOIN doctors d ON d.doctor_id = a.doctor_id
     LEFT JOIN services sv ON sv.service_id = s.service_id;

