CREATE OR REPLACE FUNCTION public.book_appointment_atomic(p_patient_name text, p_slot_id bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_doctor_id BIGINT;
    v_appointment_date DATE;
    v_appointment_time TIME;
    v_appointment_id BIGINT;
BEGIN

    -- Claim the slot only if it is still available.
    UPDATE slots
    SET available = FALSE
    WHERE slot_id = p_slot_id
      AND available = TRUE
    RETURNING
        doctor_id,
        appointment_date,
        appointment_time
    INTO
        v_doctor_id,
        v_appointment_date,
        v_appointment_time;


    -- If no row was updated, the slot was unavailable
    -- or did not exist.
    IF NOT FOUND THEN

        RETURN jsonb_build_object(
            'success', FALSE,
            'reason', 'Slot is no longer available'
        );

    END IF;


    -- Create the appointment.
    INSERT INTO appointments (
        patient_name,
        doctor_id,
        slot_id
    )
    VALUES (
        p_patient_name,
        v_doctor_id,
        p_slot_id
    )
    RETURNING appointment_id
    INTO v_appointment_id;


    RETURN jsonb_build_object(
        'success', TRUE,
        'appointment_id', v_appointment_id,
        'patient_name', p_patient_name,
        'doctor_id', v_doctor_id,
        'slot_id', p_slot_id,
        'appointment_date', v_appointment_date,
        'appointment_time', v_appointment_time
    );

END;
$function$;

CREATE OR REPLACE FUNCTION public.book_appointment_with_reason_atomic(p_patient_name text, p_slot_id bigint, p_reason_for_visit text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO 'pg_catalog', 'public', 'pg_temp'
AS $function$
DECLARE v_result jsonb; v_reason text;
BEGIN
 v_reason := nullif(btrim(p_reason_for_visit), '');
 IF length(v_reason) > 1000 THEN
   RETURN jsonb_build_object('success',false,'reason','The stated reason is too long');
 END IF;
 v_result := public.book_appointment_atomic(p_patient_name,p_slot_id);
 IF v_result->>'success' = 'true' THEN
   UPDATE public.appointments
   SET reason_for_visit = v_reason
   WHERE appointment_id = (v_result->>'appointment_id')::bigint;
   IF NOT FOUND THEN
     RAISE EXCEPTION 'Booking result has no matching appointment; entire transaction rolled back';
   END IF;
   RETURN v_result || jsonb_build_object('reason_for_visit',v_reason);
 END IF;
 RETURN v_result;
END;
$function$;

CREATE OR REPLACE FUNCTION public.cancel_appointment_atomic(p_appointment_id bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_slot_id BIGINT;
    v_patient_name TEXT;
    v_doctor_id BIGINT;
BEGIN

    SELECT
        slot_id,
        patient_name,
        doctor_id
    INTO
        v_slot_id,
        v_patient_name,
        v_doctor_id
    FROM appointments
    WHERE appointment_id = p_appointment_id
      AND status = 'booked'
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN jsonb_build_object(
            'success', FALSE,
            'reason', 'Appointment is not currently booked'
        );
    END IF;

    UPDATE appointments
    SET status = 'cancelled'
    WHERE appointment_id = p_appointment_id;

    UPDATE slots
    SET available = TRUE
    WHERE slot_id = v_slot_id;

    RETURN jsonb_build_object(
        'success', TRUE,
        'appointment_id', p_appointment_id,
        'patient_name', v_patient_name,
        'doctor_id', v_doctor_id,
        'slot_id', v_slot_id,
        'status', 'cancelled'
    );

END;
$function$;

CREATE OR REPLACE FUNCTION public.clinic_appointment_details_stamp_v1()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'pg_catalog'
AS $function$
BEGIN
 IF TG_OP = 'INSERT' THEN
   NEW.updated_at := clock_timestamp();
   NEW.last_action := CASE WHEN NEW.status = 'booked' THEN 'booked' ELSE 'created' END;
   NEW.last_rescheduled_at := NULL;
   NEW.reschedule_count := 0;
 ELSE
   -- Derived metadata is controlled by the database, not by callers.
   NEW.updated_at := OLD.updated_at;
   NEW.last_action := OLD.last_action;
   NEW.last_rescheduled_at := OLD.last_rescheduled_at;
   NEW.reschedule_count := OLD.reschedule_count;
   IF NEW.slot_id IS DISTINCT FROM OLD.slot_id THEN
     NEW.last_action := 'rescheduled';
     NEW.last_rescheduled_at := clock_timestamp();
     NEW.reschedule_count := OLD.reschedule_count + 1;
   ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
     NEW.last_action := CASE WHEN NEW.status = 'cancelled' THEN 'cancelled' ELSE 'status_changed' END;
   ELSIF NEW.patient_name IS DISTINCT FROM OLD.patient_name
      OR NEW.doctor_id IS DISTINCT FROM OLD.doctor_id
      OR NEW.reason_for_visit IS DISTINCT FROM OLD.reason_for_visit THEN
     NEW.last_action := 'details_updated';
   ELSE
     RETURN NEW;
   END IF;
   NEW.updated_at := clock_timestamp();
 END IF;
 RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.clinic_appointment_history_v1()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog'
AS $function$
DECLARE
 v_old jsonb;
 v_new jsonb;
BEGIN
 IF TG_OP = 'UPDATE' AND NEW.slot_id IS NOT DISTINCT FROM OLD.slot_id
    AND NEW.status IS NOT DISTINCT FROM OLD.status
    AND NEW.patient_name IS NOT DISTINCT FROM OLD.patient_name
    AND NEW.doctor_id IS NOT DISTINCT FROM OLD.doctor_id
    AND NEW.reason_for_visit IS NOT DISTINCT FROM OLD.reason_for_visit THEN
   RETURN NEW;
 END IF;
 IF TG_OP = 'UPDATE' THEN
   SELECT to_jsonb(OLD) || jsonb_build_object(
     'appointment_date', s.appointment_date, 'appointment_time', s.appointment_time,
     'service_name', sv.service_name, 'doctor_name', d.doctor_name,
     'consultation_mode', s.consultation_mode)
   INTO v_old FROM public.slots s
   LEFT JOIN public.services sv ON sv.service_id = s.service_id
   LEFT JOIN public.doctors d ON d.doctor_id = OLD.doctor_id
   WHERE s.slot_id = OLD.slot_id;
   v_old := coalesce(v_old, to_jsonb(OLD));
 END IF;
 SELECT to_jsonb(NEW) || jsonb_build_object(
   'appointment_date', s.appointment_date, 'appointment_time', s.appointment_time,
   'service_name', sv.service_name, 'doctor_name', d.doctor_name,
   'consultation_mode', s.consultation_mode)
 INTO v_new FROM public.slots s
 LEFT JOIN public.services sv ON sv.service_id = s.service_id
 LEFT JOIN public.doctors d ON d.doctor_id = NEW.doctor_id
 WHERE s.slot_id = NEW.slot_id;
 v_new := coalesce(v_new, to_jsonb(NEW));
 INSERT INTO public.appointment_change_history (
   appointment_id, action, old_slot_id, new_slot_id,
   old_status, new_status, old_details, new_details
 ) VALUES (
   NEW.appointment_id, NEW.last_action,
   CASE WHEN TG_OP = 'UPDATE' THEN OLD.slot_id ELSE NULL END,
   NEW.slot_id, CASE WHEN TG_OP = 'UPDATE' THEN OLD.status ELSE NULL END,
   NEW.status, v_old, v_new
 );
 RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.reschedule_appointment_atomic(p_appointment_id bigint, p_new_slot_id bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_old_slot_id BIGINT;
    v_patient_name TEXT;
    v_doctor_id BIGINT;

    v_new_doctor_id BIGINT;
    v_new_date DATE;
    v_new_time TIME;
BEGIN

    -- --------------------------------------------------------
    -- LOCK CURRENT BOOKED APPOINTMENT
    -- --------------------------------------------------------

    SELECT
        slot_id,
        patient_name,
        doctor_id
    INTO
        v_old_slot_id,
        v_patient_name,
        v_doctor_id
    FROM appointments
    WHERE appointment_id = p_appointment_id
      AND status = 'booked'
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN jsonb_build_object(
            'success', FALSE,
            'reason', 'Appointment is not currently booked'
        );
    END IF;


    -- --------------------------------------------------------
    -- DO NOT RESCHEDULE TO SAME SLOT
    -- --------------------------------------------------------

    IF v_old_slot_id = p_new_slot_id THEN
        RETURN jsonb_build_object(
            'success', FALSE,
            'reason', 'New slot is the same as the current slot'
        );
    END IF;


    -- --------------------------------------------------------
    -- CLAIM NEW SLOT ONLY IF AVAILABLE
    -- --------------------------------------------------------

    UPDATE slots
    SET available = FALSE
    WHERE slot_id = p_new_slot_id
      AND available = TRUE
    RETURNING
        doctor_id,
        appointment_date,
        appointment_time
    INTO
        v_new_doctor_id,
        v_new_date,
        v_new_time;

    IF NOT FOUND THEN
        RETURN jsonb_build_object(
            'success', FALSE,
            'reason', 'New slot is no longer available'
        );
    END IF;


    -- --------------------------------------------------------
    -- RELEASE OLD SLOT
    -- --------------------------------------------------------

    UPDATE slots
    SET available = TRUE
    WHERE slot_id = v_old_slot_id;


    -- --------------------------------------------------------
    -- UPDATE APPOINTMENT
    -- --------------------------------------------------------

    UPDATE appointments
    SET
        slot_id = p_new_slot_id,
        doctor_id = v_new_doctor_id,
        status = 'booked'
    WHERE appointment_id = p_appointment_id;


    -- --------------------------------------------------------
    -- RETURN RESULT
    -- --------------------------------------------------------

    RETURN jsonb_build_object(
        'success', TRUE,
        'appointment_id', p_appointment_id,
        'patient_name', v_patient_name,
        'old_slot_id', v_old_slot_id,
        'new_slot_id', p_new_slot_id,
        'doctor_id', v_new_doctor_id,
        'appointment_date', v_new_date,
        'appointment_time', v_new_time
    );

END;
$function$;

